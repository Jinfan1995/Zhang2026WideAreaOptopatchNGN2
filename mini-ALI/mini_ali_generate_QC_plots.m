function fig_handles = mini_ali_generate_QC_plots( ...
    reference_image, ...
    Binary_mask, ...
    regions, ...
    COMs, ...
    clust_idx, ...
    footprint_center, ...
    cell_traces, ...
    fps, ...
    qc_folder, ...
    fov_id, ...
    plot_mode, ...
    varargin)

% MINI_ALI_GENERATE_QC_PLOTS
%
% Generate standardized mini-ALI QC figures.
%
% ==========================================================
% INPUTS
% ==========================================================
%
% reference_image
%       2-D reference fluorescence image
%
% Binary_mask
%       binary segmentation mask
%
% regions
%       regionprops structure
%
% COMs
%       localized spikes:
%       [row, col, frame, amplitude]
%
% clust_idx
%       ALI cluster assignment for each row of COMs
%
% footprint_center
%       final ALI cell centers:
%       [row, col]
%
% cell_traces
%       Ncell x Nframe extracted traces
%
% fps
%       acquisition frame rate
%
% qc_folder
%       directory for saving QC figures
%
% fov_id
%       unique FOV ID
%
% plot_mode
%
%       "segmentation"
%           segmentation mask + candidate labels
%
%       "clusters"
%           localized spikes colored by ALI cluster
%
%       "centers"
%           final ALI cell centers
%
%       "traces"
%           extracted traces
%
%       "qc"
%           combined 2 x 2 QC summary only
%
%       "individual"
%           all four individual figures
%
%       "all"
%           all four individual figures + QC summary
%
%       Multiple specific figures can also be requested:
%
%           ["clusters","traces"]
%
%
% ==========================================================
% OPTIONAL NAME-VALUE INPUTS
% ==========================================================
%
% 'Visible'
%       "on" / "off"
%       default = "off"
%
% 'Save'
%       true / false
%       default = true
%
% 'SaveFIG'
%       save MATLAB .fig in addition to PNG
%       default = false
%
% 'Resolution'
%       PNG export resolution
%       default = 200
%
% 'LabelRegions'
%       label candidate segmented regions
%       default = true
%
% 'LabelCells'
%       label final ALI cells
%       default = true
%
% 'MaxTraceDisplay'
%       maximum number of traces displayed in QC summary
%       default = 100
%
%
% ==========================================================
% OUTPUT
% ==========================================================
%
% fig_handles
%
%       structure containing generated figure handles
%
%
% ==========================================================
% EXAMPLES
% ==========================================================
%
% Combined QC only:
%
% mini_ali_generate_QC_plots( ...
%     reference_image, ...
%     Binary_mask, ...
%     regions, ...
%     COMs, ...
%     clust_idx, ...
%     footprint_center, ...
%     cell_traces, ...
%     fps, ...
%     qc_folder, ...
%     fov_id, ...
%     "qc");
%
%
% Cluster plot only:
%
% mini_ali_generate_QC_plots( ...
%     reference_image, ...
%     Binary_mask, ...
%     regions, ...
%     COMs, ...
%     clust_idx, ...
%     footprint_center, ...
%     cell_traces, ...
%     fps, ...
%     qc_folder, ...
%     fov_id, ...
%     "clusters", ...
%     'Visible',"on");
%
%
% Generate all:
%
% mini_ali_generate_QC_plots( ...
%     reference_image, ...
%     Binary_mask, ...
%     regions, ...
%     COMs, ...
%     clust_idx, ...
%     footprint_center, ...
%     cell_traces, ...
%     fps, ...
%     qc_folder, ...
%     fov_id, ...
%     "all");


%% =========================================================
% Parse optional parameters
% ==========================================================

p = inputParser;

addParameter( ...
    p, ...
    'Visible', ...
    "off");

addParameter( ...
    p, ...
    'Save', ...
    true);

addParameter( ...
    p, ...
    'SaveFIG', ...
    false);

addParameter( ...
    p, ...
    'Resolution', ...
    200);

addParameter( ...
    p, ...
    'LabelRegions', ...
    true);

addParameter( ...
    p, ...
    'LabelCells', ...
    true);

addParameter( ...
    p, ...
    'MaxTraceDisplay', ...
    100);

parse(p,varargin{:});

opt = p.Results;


%% =========================================================
% Create output folder
% ==========================================================

if opt.Save && ~exist(qc_folder,'dir')
    mkdir(qc_folder);
end


%% =========================================================
% Normalize plot mode
% ==========================================================

plot_mode = lower(string(plot_mode));


if any(plot_mode == "all")

    plot_mode = [ ...
        "segmentation", ...
        "clusters", ...
        "centers", ...
        "traces", ...
        "qc"];

elseif any(plot_mode == "individual")

    plot_mode = [ ...
        "segmentation", ...
        "clusters", ...
        "centers", ...
        "traces"];

end


plot_mode = unique( ...
    plot_mode, ...
    'stable');


%% =========================================================
% Validate plot mode
% ==========================================================

valid_modes = [ ...
    "segmentation", ...
    "clusters", ...
    "centers", ...
    "traces", ...
    "qc"];


invalid_modes = ...
    plot_mode( ...
    ~ismember(plot_mode,valid_modes));


if ~isempty(invalid_modes)

    error( ...
        'Unknown QC plot mode: %s', ...
        strjoin(invalid_modes,", "));

end


%% =========================================================
% Basic counts
% ==========================================================

nRegions = numel(regions);


if isempty(COMs)

    nSpikes = 0;

else

    nSpikes = size(COMs,1);

end


if isempty(footprint_center)

    nCells = 0;

else

    nCells = size(footprint_center,1);

end


if isempty(clust_idx)

    nClusters = 0;

else

    nClusters = double(max(clust_idx));

end


%% =========================================================
% Reference-image display limits
% ==========================================================

reference_single = ...
    single(reference_image);


display_limits = ...
    prctile( ...
    reference_single(:), ...
    [1 99.8]);


if ~all(isfinite(display_limits)) || ...
        display_limits(1) == display_limits(2)

    display_limits = [ ...
        min(reference_single(:)), ...
        max(reference_single(:))];

end


%% =========================================================
% Region centroids
% ==========================================================

if nRegions > 0

    region_centroids = ...
        reshape( ...
        [regions.Centroid], ...
        2, ...
        [])';

else

    region_centroids = ...
        zeros(0,2);

end


%% =========================================================
% Figure output structure
% ==========================================================

fig_handles = struct;


%% =========================================================
% 1. SEGMENTATION QC
% ==========================================================

if any(plot_mode == "segmentation")

    fig = figure( ...
        'Visible',char(opt.Visible), ...
        'Color','w', ...
        'Position',[100 100 1000 850]);


    ax = axes(fig);


    imshow( ...
        reference_image, ...
        display_limits, ...
        'Parent',ax, ...
        'InitialMagnification','fit');


    hold(ax,'on');


    %% Segmentation boundaries

    boundaries = ...
        bwboundaries(Binary_mask);


    for i = 1:numel(boundaries)

        b = boundaries{i};

        plot( ...
            ax, ...
            b(:,2), ...
            b(:,1), ...
            '-', ...
            'Color',[0 1 0], ...
            'LineWidth',0.5);

    end


    %% Candidate region centers

    if nRegions > 0

        scatter( ...
            ax, ...
            region_centroids(:,1), ...
            region_centroids(:,2), ...
            12, ...
            'r', ...
            'filled');


        %% Candidate labels

        if opt.LabelRegions

            for i = 1:nRegions

                text( ...
                    ax, ...
                    region_centroids(i,1)+3, ...
                    region_centroids(i,2), ...
                    num2str(i), ...
                    'Color',[1 1 0], ...
                    'FontSize',7, ...
                    'Clipping','on');

            end

        end

    end


    title( ...
        ax, ...
        sprintf( ...
        '%s | Segmentation | %d candidate regions', ...
        fov_id, ...
        nRegions), ...
        'Interpreter','none');


    axis(ax,'image');
    axis(ax,'off');


    hold(ax,'off');


    fig_handles.segmentation = fig;


    save_figure( ...
        fig, ...
        qc_folder, ...
        "01_segmentation", ...
        opt);

end


%% =========================================================
% 2. ALI SPIKE CLUSTER PLOT
% ==========================================================

if any(plot_mode == "clusters")

    fig = figure( ...
        'Visible',char(opt.Visible), ...
        'Color','w', ...
        'Position',[100 100 1000 850]);


    ax = axes(fig);


    mini_ali_plot_cluster( ...
        reference_image, ...
        COMs, ...
        clust_idx, ...
        ax);


    title( ...
        ax, ...
        sprintf( ...
        '%s | ALI clusters | %d spikes | %d clusters', ...
        fov_id, ...
        nSpikes, ...
        nClusters), ...
        'Interpreter','none');


    fig_handles.clusters = fig;


    save_figure( ...
        fig, ...
        qc_folder, ...
        "02_ALI_spike_clusters", ...
        opt);

end


%% =========================================================
% 3. FINAL ALI CELL CENTERS
% ==========================================================

if any(plot_mode == "centers")

    fig = figure( ...
        'Visible',char(opt.Visible), ...
        'Color','w', ...
        'Position',[100 100 1000 850]);


    ax = axes(fig);


    imshow( ...
        reference_image, ...
        display_limits, ...
        'Parent',ax, ...
        'InitialMagnification','fit');


    hold(ax,'on');


    if nCells > 0

        %% Cell centers

        scatter( ...
            ax, ...
            footprint_center(:,2), ...
            footprint_center(:,1), ...
            45, ...
            'o', ...
            'MarkerEdgeColor',[0 1 1], ...
            'LineWidth',1);


        %% Cell labels

        if opt.LabelCells

            for i = 1:nCells

                text( ...
                    ax, ...
                    footprint_center(i,2)+4, ...
                    footprint_center(i,1), ...
                    num2str(i), ...
                    'Color',[1 1 0], ...
                    'FontSize',7, ...
                    'Clipping','on');

            end

        end

    end


    title( ...
        ax, ...
        sprintf( ...
        '%s | Final ALI cells | %d cells', ...
        fov_id, ...
        nCells), ...
        'Interpreter','none');


    axis(ax,'image');
    axis(ax,'off');


    hold(ax,'off');


    fig_handles.centers = fig;


    save_figure( ...
        fig, ...
        qc_folder, ...
        "03_final_cell_centers", ...
        opt);

end


%% =========================================================
% 4. EXTRACTED CELL TRACES
% ==========================================================

if any(plot_mode == "traces")

    fig = figure( ...
        'Visible',char(opt.Visible), ...
        'Color','w', ...
        'Position',[100 100 1400 900]);


    ax = axes(fig);


    if isempty(cell_traces)

        axis(ax,'off');


        text( ...
            ax, ...
            0.5, ...
            0.5, ...
            'No extracted cell traces', ...
            'HorizontalAlignment','center', ...
            'Units','normalized');

    else

        plot_stacked_traces( ...
            ax, ...
            cell_traces, ...
            fps, ...
            inf);


        title( ...
            ax, ...
            sprintf( ...
            '%s | Extracted traces | %d cells', ...
            fov_id, ...
            size(cell_traces,1)), ...
            'Interpreter','none');

    end


    fig_handles.traces = fig;


    save_figure( ...
        fig, ...
        qc_folder, ...
        "04_cell_traces", ...
        opt);

end


%% =========================================================
% 5. COMBINED QC SUMMARY
% ==========================================================

if any(plot_mode == "qc")

    fig = figure( ...
        'Visible',char(opt.Visible), ...
        'Color','w', ...
        'Position',[50 50 1600 1050]);


    tl = tiledlayout( ...
        fig, ...
        2, ...
        2, ...
        'TileSpacing','compact', ...
        'Padding','compact');


    %% =====================================================
    % A. Segmentation
    % ======================================================

    ax1 = nexttile(tl);


    imshow( ...
        reference_image, ...
        display_limits, ...
        'Parent',ax1);


    hold(ax1,'on');


    boundaries = ...
        bwboundaries(Binary_mask);


    for i = 1:numel(boundaries)

        b = boundaries{i};

        plot( ...
            ax1, ...
            b(:,2), ...
            b(:,1), ...
            '-', ...
            'Color',[0 1 0], ...
            'LineWidth',0.35);

    end


    if nRegions > 0

        scatter( ...
            ax1, ...
            region_centroids(:,1), ...
            region_centroids(:,2), ...
            7, ...
            'r', ...
            'filled');

    end


    title( ...
        ax1, ...
        sprintf( ...
        'Segmentation: %d candidates', ...
        nRegions));


    axis(ax1,'image');
    axis(ax1,'off');


    hold(ax1,'off');


    %% =====================================================
    % B. ALI spike clusters
    % ======================================================

    ax2 = nexttile(tl);


    mini_ali_plot_cluster( ...
        reference_image, ...
        COMs, ...
        clust_idx, ...
        ax2);


    title( ...
        ax2, ...
        sprintf( ...
        'ALI clusters: %d | spikes: %d', ...
        nClusters, ...
        nSpikes));


    %% =====================================================
    % C. Final ALI cell centers
    % ======================================================

    ax3 = nexttile(tl);


    imshow( ...
        reference_image, ...
        display_limits, ...
        'Parent',ax3);


    hold(ax3,'on');


    if nCells > 0

        scatter( ...
            ax3, ...
            footprint_center(:,2), ...
            footprint_center(:,1), ...
            30, ...
            'o', ...
            'MarkerEdgeColor',[0 1 1], ...
            'LineWidth',0.8);

    end


    title( ...
        ax3, ...
        sprintf( ...
        'Final ALI cells: %d', ...
        nCells));


    axis(ax3,'image');
    axis(ax3,'off');


    hold(ax3,'off');


    %% =====================================================
    % D. Extracted traces
    % ======================================================

    ax4 = nexttile(tl);


    if isempty(cell_traces)

        axis(ax4,'off');


        text( ...
            ax4, ...
            0.5, ...
            0.5, ...
            'No extracted cell traces', ...
            'HorizontalAlignment','center', ...
            'Units','normalized');

    else

        plot_stacked_traces( ...
            ax4, ...
            cell_traces, ...
            fps, ...
            opt.MaxTraceDisplay);

    end


    title( ...
        ax4, ...
        sprintf( ...
        'Extracted traces: %d cells', ...
        size(cell_traces,1)));


    %% =====================================================
    % Overall title
    % ======================================================

    title( ...
        tl, ...
        sprintf( ...
        '%s | mini-ALI QC', ...
        fov_id), ...
        'Interpreter','none', ...
        'FontWeight','bold');


    fig_handles.qc = fig;


    save_figure( ...
        fig, ...
        qc_folder, ...
        "00_QC_summary", ...
        opt);

end


end



%% =========================================================
% LOCAL FUNCTION
% Plot vertically stacked traces
% ==========================================================

function plot_stacked_traces( ...
    ax, ...
    cell_traces, ...
    fps, ...
    max_display)


traces = ...
    single(cell_traces);


nCells = size(traces,1);
nFrames = size(traces,2);


%% =========================================================
% Select cells to display
% ==========================================================

if isfinite(max_display) && ...
        nCells > max_display

    display_idx = ...
        unique( ...
        round( ...
        linspace( ...
        1, ...
        nCells, ...
        max_display)));

else

    display_idx = ...
        1:nCells;

end


traces = ...
    traces(display_idx,:);


nDisplay = ...
    size(traces,1);


%% =========================================================
% Normalize each trace to 0-1
% ==========================================================

trace_min = ...
    min( ...
    traces, ...
    [], ...
    2);


trace_max = ...
    max( ...
    traces, ...
    [], ...
    2);


trace_range = ...
    trace_max - trace_min;


%% Protect flat or invalid traces

bad_range = ...
    trace_range == 0 | ...
    ~isfinite(trace_range);


trace_range(bad_range) = 1;


traces_norm = ...
    (traces - trace_min) ...
    ./ trace_range;


%% =========================================================
% Vertical offsets
% ==========================================================

trace_spacing = ...
    single(1.15);


offsets = ...
    single((0:nDisplay-1)') ...
    .* trace_spacing;


traces_plot = ...
    traces_norm ...
    + offsets;


%% =========================================================
% Time axis
% ==========================================================

time_s = ...
    (0:nFrames-1) ...
    ./ double(fps);


%% =========================================================
% Plot
% ==========================================================

plot( ...
    ax, ...
    time_s, ...
    traces_plot', ...
    'Color',[0.15 0.15 0.15], ...
    'LineWidth',0.4);


xlabel( ...
    ax, ...
    'Time (s)');


ylabel( ...
    ax, ...
    'Cell');


box( ...
    ax, ...
    'off');


%% X limits

if nFrames > 1

    xlim( ...
        ax, ...
        [ ...
        time_s(1), ...
        time_s(end)]);

end


%% Y limits

if nDisplay > 0

    ylim( ...
        ax, ...
        [ ...
        -0.5, ...
        double(offsets(end))+1.5]);

end


%% =========================================================
% Cell-number labels
% ==========================================================

max_labels = 20;


label_step = ...
    max( ...
    1, ...
    ceil( ...
    nDisplay / max_labels));


label_rows = ...
    1:label_step:nDisplay;


if ~isempty(label_rows)

    yticks( ...
        ax, ...
        double(offsets(label_rows)) + 0.5);


    %% Keep original cell indices even when subsampling traces

    yticklabels( ...
        ax, ...
        string( ...
        display_idx(label_rows)));

end


end



%% =========================================================
% LOCAL FUNCTION
% Save figure
% ==========================================================

function save_figure( ...
    fig, ...
    qc_folder, ...
    filename, ...
    opt)


if ~opt.Save
    return
end


%% =========================================================
% PNG
% ==========================================================

exportgraphics( ...
    fig, ...
    fullfile( ...
        qc_folder, ...
        filename + ".png"), ...
    'Resolution', ...
    opt.Resolution);


%% =========================================================
% Optional MATLAB .fig
% ==========================================================

if opt.SaveFIG

    savefig( ...
        fig, ...
        fullfile( ...
            qc_folder, ...
            filename + ".fig"));

end


end